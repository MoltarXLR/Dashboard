// Generates ../worldmask.js: a COLS x ROWS land/ocean dot grid (equirectangular)
// from Natural Earth coastlines (world-atlas). Usage:
//   cd tools && npm install && node gen-worldmask.mjs [cols=60] [rows=30] [latTop=84] [latBottom=-60]
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";
import { geoContains } from "d3-geo";

const [cols = 60, rows = 30, latTop = 84, latBottom = -60] = process.argv.slice(2).map(Number);
const SAMPLES = 4; // SAMPLES x SAMPLES probe points per cell
const THRESHOLD = 0.2; // fraction of probes on land for a cell to count as land

const require = createRequire(import.meta.url);
const world = JSON.parse(readFileSync(require.resolve("world-atlas/land-110m.json"), "utf8"));
const land = feature(world, world.objects.land);

const lonStep = 360 / cols;
const latStep = (latTop - latBottom) / rows;
const grid = [];
for (let r = 0; r < rows; r++) {
  let line = "";
  for (let c = 0; c < cols; c++) {
    let hits = 0;
    for (let i = 0; i < SAMPLES; i++) {
      for (let j = 0; j < SAMPLES; j++) {
        const lon = -180 + (c + (j + 0.5) / SAMPLES) * lonStep;
        const lat = latTop - (r + (i + 0.5) / SAMPLES) * latStep;
        if (geoContains(land, [lon, lat])) hits++;
      }
    }
    line += hits / SAMPLES ** 2 >= THRESHOLD ? "#" : ".";
  }
  grid.push(line);
}

const out =
  `// Generated by tools/gen-worldmask.mjs from Natural Earth 1:110m land (world-atlas). Do not edit by hand.\n` +
  `// "#" = land, "." = ocean. Equirectangular: ${lonStep}° lon x ${latStep}° lat per dot.\n` +
  `window.WORLD_MASK = ${JSON.stringify({ cols, rows, latTop, latBottom, grid }, null, 2)};\n`;
writeFileSync(new URL("../worldmask.js", import.meta.url), out);
console.log(grid.join("\n"));
